class Calculadora {
  int? somar(int n1, int n2) {
    int rs;
    return rs = n1 + n2;
  }

  int? subtrair(int n1, int n2) {
    int rs;
    return rs = n1 - n2;
  }

  int? mult(int n1, int n2) {
    int rs;
    return rs = n1 * n2;
  }

  double? div(double n1, double n2) {
    double rs;
    return rs = n1 / n2;
  }
}
